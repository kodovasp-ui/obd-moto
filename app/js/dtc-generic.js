//   1. app/js/dtc-kb.js (E)  — πλήρεις εγγραφές με αιτίες και βήματα ελέγχου
//   2. TITLES (εδώ)          — τίτλος κωδικού, χωρίς αιτίες/βήματα
//   3. FAMILIES (εδώ)        — οικογένειες με απόλυτα συστηματική δομή
//                              (ανά κύλινδρο, ανά bank/αισθητήρα, ανά πηνίο)
//   4. RANGES (εδώ)          — αν δεν ξέρουμε τον κωδικό, λέμε τουλάχιστον το υποσύστημα
