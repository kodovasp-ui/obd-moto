/** Το υποσύστημα του κωδικού από το εύρος του, ή null. */
export function subsystem(code) {
  const m = String(code).toUpperCase().match(/^([PCBU])([0-9A-F]{4})$/);
  if (!m) return null;
  const n = parseInt(m[2], 10);
  if (!Number.isFinite(n) || /[A-F]/.test(m[2])) return null;
  return (RANGES[m[1]] || []).find(([lo, hi]) => n >= lo && n <= hi)?.[2] || null;
}

/**
 * Τυποποιημένος κωδικός SAE ή ειδικός κατασκευαστή, από τον δεύτερο χαρακτήρα.
 * P: 0, 2 και 3 είναι τυποποιημένοι. C/B/U: μόνο το 0 (1 και 2 είναι του κατασκευαστή).
 */
export function isGeneric(code) {
  const c = String(code).toUpperCase();
  return c[0] === 'P' ? ['0', '2', '3'].includes(c[1]) : c[1] === '0';
}

/** Τίτλος γενικού κωδικού: ρητός πίνακας → οικογένεια → null. */
export function genericTitle(code) {
  const c = String(code).toUpperCase();
  return TITLES[c] || family(c) || null;
}

/** Πόσους κωδικούς καλύπτουμε (για την ένδειξη κάλυψης στο UI). */
export function coverage() {
  let fam = 0;
  for (const sys of ['P']) {
    for (let n = 1; n <= 3499; n++) {
      const c = sys + String(n).padStart(4, '0');
      if (!TITLES[c] && family(c)) fam++;
    }
  }
  return { titles: Object.keys(TITLES).length, families: fam };
}
