// Δεν εφευρίσκουμε περιγραφές: ό,τι δεν καλύπτεται μένει «άγνωστος» με το εύρος του.

// ---------------------------------------------------------------- 3. οικογένειες
const O2_FAULTS = [
  'κύκλωμα — δυσλειτουργία', 'χαμηλή τάση', 'υψηλή τάση',
  'αργή απόκριση', 'καμία δραστηριότητα', 'δυσλειτουργία θέρμανσης',
];
const O2_BLOCKS = { 130: 'B1S1', 136: 'B1S2', 142: 'B1S3', 150: 'B2S1', 156: 'B2S2', 162: 'B2S3' };

const INJ_FAULTS = ['χαμηλή τάση κυκλώματος', 'υψηλή τάση κυκλώματος', 'συμμετοχή/ισορροπία'];
const COIL_LETTER = 'ABCDEFGHIJKL';

/** Κωδικοί που παράγονται από απόλυτα συστηματική δομή του J2012. */
function family(code) {
  const m = code.match(/^([PCBU])([0-9A-F]{4})$/);
  if (!m) return null;
  const [, sys, hex] = m;
  const n = parseInt(hex, 10);               // οι οικογένειες εδώ είναι όλες δεκαδικές
  if (!Number.isFinite(n) || /[A-F]/.test(hex)) return null;

  if (sys === 'P') {
    // Αφλογιστία ανά κύλινδρο: P0301-P0312
    if (n >= 301 && n <= 312) return `Αφλογιστία κυλίνδρου ${n - 300}`;
    // Κύκλωμα μπεκ ανοιχτό ανά κύλινδρο: P0201-P0212
    if (n >= 201 && n <= 212) return `Κύκλωμα μπεκ κυλίνδρου ${n - 200} — ανοιχτό`;
    // Μπεκ χαμηλή/υψηλή/ισορροπία ανά κύλινδρο: P0261 + 3×(κύλινδρος−1)
    if (n >= 261 && n <= 290) {
      const cyl = Math.floor((n - 261) / 3) + 1;
      return `Μπεκ κυλίνδρου ${cyl} — ${INJ_FAULTS[(n - 261) % 3]}`;
    }
    // Αισθητήρες λάμδα: 6 σφάλματα × 6 θέσεις
    for (const [base, pos] of Object.entries(O2_BLOCKS)) {
      const b = +base;
      if (n >= b && n <= b + 5) return `Αισθητήρας λάμδα ${pos} — ${O2_FAULTS[n - b]}`;
    }
    // Πολλαπλασιαστές A–L: P0351-P0362
    if (n >= 351 && n <= 362) {
      return `Πολλαπλασιαστής ${COIL_LETTER[n - 351]} — κύκλωμα πρωτεύοντος/δευτερεύοντος`;
    }
    // Πολλαπλασιαστές χαμηλή/υψηλή: P2300 + 3×(πηνίο−1)
    if (n >= 2300 && n <= 2333 && (n - 2300) % 3 !== 2) {
      const coil = Math.floor((n - 2300) / 3);
      return `Πολλαπλασιαστής ${COIL_LETTER[coil]} — ${(n - 2300) % 3 === 0 ? 'χαμηλή' : 'υψηλή'} τάση πρωτεύοντος`;
    }
    // Προθερμαντήρες (diesel) ανά κύλινδρο: P0671-P0682
    if (n >= 671 && n <= 682) return `Κύκλωμα προθερμαντήρα κυλίνδρου ${n - 670}`;
    // Σχέσεις μετάδοσης: P0731-P0736
    if (n >= 731 && n <= 736) return `Λάθος σχέση μετάδοσης — ${n === 736 ? 'όπισθεν' : `${n - 730}η`}`;
    // Απενεργοποίηση κυλίνδρων: P3401 + 4×(κύλινδρος−1)
    if (n >= 3401 && n <= 3448) {
      const cyl = Math.floor((n - 3401) / 4) + 1;
      const f = ['κύκλωμα ενεργοποίησης', 'εύρος/απόδοση', 'χαμηλή τάση', 'υψηλή τάση'][(n - 3401) % 4];
      return `Απενεργοποίηση κυλίνδρου ${cyl} — ${f}`;
    }
  }
  return null;
}

