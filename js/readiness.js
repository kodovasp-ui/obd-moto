export function monitorInfo(name) {
  return MONITOR_INFO[name] || { what: 'Monitor του συστήματος εκπομπών.', how: 'Δες το εγχειρίδιο σέρβις για το drive cycle.' };
}

/** Χωρίζει τα monitors σε ολοκληρωμένα και εκκρεμή, με οδηγίες για τα εκκρεμή. */
export function readinessPlan(status) {
  if (!status) return null;
  const items = status.monitors.map((m) => ({ ...m, ...monitorInfo(m.name) }));
  const done = items.filter((m) => m.complete);
  const todo = items.filter((m) => !m.complete);
  return {
    done, todo, total: items.length,
    ready: todo.length === 0,
    // Τα συνεχή monitors ολοκληρώνονται αμέσως· τα μη συνεχή θέλουν drive cycle.
    needsDriving: todo.filter((m) => !m.cont),
    mil: status.mil,
    // Πολλές χώρες απορρίπτουν στο ΚΤΕΟ με αναμμένη MIL ή με >1 μη ολοκληρωμένο monitor.
    verdict: status.mil
      ? 'Η λυχνία βλάβης είναι αναμμένη — το ΚΤΕΟ θα απορρίψει.'
      : todo.length === 0
        ? 'Όλα τα monitors ολοκληρωμένα και η λυχνία σβηστή.'
        : `${todo.length} monitor${todo.length > 1 ? 's' : ''} δεν έχουν ολοκληρωθεί.`,
  };
}
